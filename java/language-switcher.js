// Language Switcher Class
class LanguageSwitcher {
    constructor() {
        // Default to Arabic ('ar') instead of English
        this.currentLanguage = localStorage.getItem('language') || 'ar';
        this.init();
    }

    init() {
        // Apply saved language on page load
        this.applyLanguage(this.currentLanguage);
        
        // Setup language switch button listeners
        this.setupEventListeners();
    }

    setupEventListeners() {
        // Listen for language toggle button clicks
        const langToggles = document.querySelectorAll('.language-toggle');
        langToggles.forEach(toggle => {
            toggle.addEventListener('click', () => {
                this.toggleLanguage();
            });
        });

        // Listen for direct language selection
        const enBtns = document.querySelectorAll('[data-lang="en"]');
        const arBtns = document.querySelectorAll('[data-lang="ar"]');
        
        enBtns.forEach(btn => {
            btn.addEventListener('click', () => this.setLanguage('en'));
        });
        
        arBtns.forEach(btn => {
            btn.addEventListener('click', () => this.setLanguage('ar'));
        });
    }

    toggleLanguage() {
        const newLang = this.currentLanguage === 'en' ? 'ar' : 'en';
        this.setLanguage(newLang);
    }

    setLanguage(lang) {
        this.currentLanguage = lang;
        localStorage.setItem('language', lang);
        this.applyLanguage(lang);
    }

    applyLanguage(lang) {
        // Update all elements with data-translate attribute
        const elements = document.querySelectorAll('[data-translate]');
        elements.forEach(element => {
            const key = element.getAttribute('data-translate');
            if (translations[lang] && translations[lang][key]) {
                // Preserve HTML structure, only change text
                if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                    element.placeholder = translations[lang][key];
                } else {
                    // Keep the element's children (like SVG icons) intact
                    const children = Array.from(element.children);
                    element.textContent = translations[lang][key];
                    children.forEach(child => element.appendChild(child));
                }
            }
        });

        // Force RTL alignment for Arabic services section
        const rtlSelectors = [
            '.services-label',
            '.services-title',
            '.services-description',
            '.services-button'
        ];
        rtlSelectors.forEach(sel => {
            const el = document.querySelector(sel);
            if (el) {
                if (lang === 'ar') {
                    el.classList.add('rtl');
                } else {
                    el.classList.remove('rtl');
                }
            }
        });

        // Force RTL alignment for Arabic about section and features
        const aboutRtlSelectors = [
            '.about-label',
            '.about-title'
        ];
        aboutRtlSelectors.forEach(sel => {
            const el = document.querySelector(sel);
            if (el) {
                if (lang === 'ar') {
                    el.classList.add('rtl');
                } else {
                    el.classList.remove('rtl');
                }
            }
        });

        // Force RTL alignment for ALL feature titles and descriptions
        document.querySelectorAll('.feature-title, .feature-description').forEach(el => {
            if (lang === 'ar') {
                el.classList.add('rtl');
            } else {
                el.classList.remove('rtl');
            }
        });

        // Force left alignment for CTA section in Arabic (Home page)
        document.querySelectorAll('.cta-section, .cta-content, .cta-text, .cta-button').forEach(el => {
            if (lang === 'ar') {
                el.classList.add('rtl');
            } else {
                el.classList.remove('rtl');
            }
        });

        // Force left alignment for Join Team section in Arabic (About Us page)
        document.querySelectorAll('.join-team-container, .join-team-content, .join-team-action').forEach(el => {
            if (lang === 'ar') {
                el.classList.add('rtl');
            } else {
                el.classList.remove('rtl');
            }
        });

        // Force RTL alignment for Arabic about us page
        const aboutUsRtlSelectors = [
            '.overview-title',
            '.card-description'
        ];
        aboutUsRtlSelectors.forEach(sel => {
            const el = document.querySelector(sel);
            if (el) {
                if (lang === 'ar') {
                    el.classList.add('rtl');
                } else {
                    el.classList.remove('rtl');
                }
            }
        });

        // Force RTL alignment for Arabic about us labels and card titles
        // Add RTL to all .overview-label, .card-title, .card-description elements
        document.querySelectorAll('.overview-label, .card-title, .card-description').forEach(el => {
            if (lang === 'ar') {
                el.classList.add('rtl');
            } else {
                el.classList.remove('rtl');
            }
        });

        // Force RTL alignment for Arabic overview description
        const overviewDesc = document.querySelector('.overview-description');
        if (overviewDesc) {
            if (lang === 'ar') {
                overviewDesc.classList.add('rtl');
            } else {
                overviewDesc.classList.remove('rtl');
            }
        }

        // Force RTL alignment for Arabic service categories
        document.querySelectorAll('.service-category-title, .service-category-desc').forEach(el => {
            if (lang === 'ar') {
                el.classList.add('rtl');
            } else {
                el.classList.remove('rtl');
            }
        });
        // Add RTL to all service category list items
        document.querySelectorAll('.service-category-list li').forEach(el => {
            if (lang === 'ar') {
                el.classList.add('rtl');
            } else {
                el.classList.remove('rtl');
            }
        });

        // Add RTL to all .service-list li elements
        document.querySelectorAll('.service-list li').forEach(el => {
            if (lang === 'ar') {
                el.classList.add('rtl');
            } else {
                el.classList.remove('rtl');
            }
        });

        // Add RTL to individual service pages (19 service detail pages)
        document.querySelectorAll('.banner-title, .service-content-container p, .service-content-container h3, .service-content-container ul, .service-content-container li, .request-message').forEach(el => {
            if (lang === 'ar') {
                el.classList.add('rtl');
            } else {
                el.classList.remove('rtl');
            }
        });

        // Add RTL to all milestone/achievement cards in missions page
        document.querySelectorAll('.goal-heading, .goal-description').forEach(el => {
            if (lang === 'ar') {
                el.classList.add('rtl');
            } else {
                el.classList.remove('rtl');
            }
        });

        // Add RTL to industries section
        document.querySelectorAll('.industries-title, .title-highlight').forEach(el => {
            if (lang === 'ar') {
                el.classList.add('rtl');
            } else {
                el.classList.remove('rtl');
            }
        });

        // Add RTL to approach section
        document.querySelectorAll('.approach-title, .approach-text').forEach(el => {
            if (lang === 'ar') {
                el.classList.add('rtl');
            } else {
                el.classList.remove('rtl');
            }
        });

        // Update language toggle button text
        const toggleBtns = document.querySelectorAll('.language-toggle .lang-text');
        toggleBtns.forEach(btn => {
            btn.textContent = lang === 'en' ? 'العربية' : 'English';
        });

        // Update active state on language buttons
        document.querySelectorAll('[data-lang]').forEach(btn => {
            if (btn.getAttribute('data-lang') === lang) {
                btn.classList.add('active');
            } else {
                btn.classList.remove('active');
            }
        });

        // Update HTML lang attribute for accessibility
        document.documentElement.lang = lang;

        // IMPORTANT: Do NOT change dir attribute - keep it ltr for both languages
        document.documentElement.dir = 'ltr';
        document.body.style.textAlign = 'left';
    }

    getCurrentLanguage() {
        return this.currentLanguage;
    }
}

