// Language management functions
window.LanguageManager = {
    currentLang: localStorage.getItem('language') || 'en',
    
    init: function() {
        this.applyLanguage(this.currentLang);
        this.setupLanguageToggle();
    },
    
    switchLanguage: function(lang) {
        this.currentLang = lang;
        localStorage.setItem('language', lang);
        this.applyLanguage(lang);
    },
    
    applyLanguage: function(lang) {
        const t = window.translations[lang];
        if (!t) return;
        
        // Apply RTL/LTR
        document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
        document.documentElement.lang = lang;
        
        // Update all translatable elements
        this.updateElements(t);
        
        // Update language toggle button
        const langBtn = document.getElementById('language-toggle');
        if (langBtn) {
            langBtn.textContent = t.language;
        }
            // Add RTL class to services section if Arabic
            var servicesLabel = document.querySelector('.services-label');
            var servicesTitle = document.querySelector('.services-title');
            var servicesDesc = document.querySelector('.services-description');
            var servicesButton = document.querySelector('.services-button');
            if (servicesLabel) {
                if (lang === 'ar') {
                    servicesLabel.classList.add('rtl');
                } else {
                    servicesLabel.classList.remove('rtl');
                }
            }
            if (servicesTitle) {
                if (lang === 'ar') {
                    servicesTitle.classList.add('rtl');
                } else {
                    servicesTitle.classList.remove('rtl');
                }
            }
            if (servicesDesc) {
                if (lang === 'ar') {
                    servicesDesc.classList.add('rtl');
                } else {
                    servicesDesc.classList.remove('rtl');
                }
            }
            if (servicesButton) {
                if (lang === 'ar') {
                    servicesButton.classList.add('rtl');
                } else {
                    servicesButton.classList.remove('rtl');
                }
            }
            // Add RTL class to hero text if Arabic
            var heroTitle = document.querySelector('.hero-title');
            var heroSubtitle = document.querySelector('.hero-subtitle');
            if (heroTitle) {
                if (lang === 'ar') {
                    heroTitle.classList.add('rtl');
                } else {
                    heroTitle.classList.remove('rtl');
                }
            }
            if (heroSubtitle) {
                if (lang === 'ar') {
                    heroSubtitle.classList.add('rtl');
                } else {
                    heroSubtitle.classList.remove('rtl');
                }
            }
    },
    
    updateElements: function(t) {
        // Navigation
        this.updateElement('nav-home', t.home);
        this.updateElement('nav-about', t.aboutUs);
        this.updateElement('nav-missions', t.missions);
        this.updateElement('nav-services', t.services);
        this.updateElement('nav-samples', t.samples);
        this.updateElement('nav-team', t.team);
        this.updateElement('nav-locations', t.locations);
        this.updateElement('nav-contact', t.contact);
        
        // Main content
        this.updateElement('main-title', t[this.getPageKey() + 'Title']);
        this.updateElement('main-description', t[this.getPageKey() + 'Description']);
        
        // Footer
        this.updateElement('footer-company', t.footerCompany);
        this.updateElement('footer-services', t.footerServices);
        this.updateElement('footer-updates', t.footerUpdates);
        this.updateElement('footer-about-us', t.footerAboutUs);
        this.updateElement('footer-why-altmate', t.footerWhyAltMate);
        this.updateElement('footer-meet-team', t.footerMeetTeam);
        this.updateElement('footer-digital-media', t.footerDigitalMedia);
        this.updateElement('footer-strategy', t.footerStrategy);
        this.updateElement('footer-development', t.footerDevelopment);
        this.updateElement('footer-rights', t.footerRights);
        this.updateElement('footer-designed', t.footerDesigned);
        
        // Email placeholder
        const emailInput = document.querySelector('.email-input');
        if (emailInput) {
            emailInput.placeholder = t.footerEmailPlaceholder;
        }
    },
    
    updateElement: function(id, text) {
        const element = document.getElementById(id);
        if (element && text) {
            element.textContent = text;
        }
    },
    
    getPageKey: function() {
        const path = window.location.pathname;
        if (path.includes('home.html') || path === '/' || path.includes('index.html')) return 'home';
        if (path.includes('aboutus.html')) return 'about';
        if (path.includes('missions.html')) return 'missions';
        if (path.includes('services.html')) return 'services';
        if (path.includes('samples.html')) return 'samples';
        if (path.includes('team.html')) return 'team';
        if (path.includes('locations.html')) return 'locations';
        if (path.includes('contact.html')) return 'contact';
        return 'home';
    },
    
    setupLanguageToggle: function() {
        const langBtn = document.getElementById('language-toggle');
        if (langBtn) {
            langBtn.addEventListener('click', () => {
                const newLang = this.currentLang === 'en' ? 'ar' : 'en';
                this.switchLanguage(newLang);
            });
        }
    }
};

